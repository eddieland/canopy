"""Prompt files, the overseer's generated state block (DESIGN §6 step 4), and worker prompts (DESIGN §8).

A prompt named `overseer.md` is read from `paths.prompt_overrides` if a file of that name is there, otherwise from the
prompts canopy ships. Worker prompts name their inputs as `{{NAME}}` placeholders.
"""

from __future__ import annotations

import json
import re
import sqlite3
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from canopy import db, resources

if TYPE_CHECKING:
    from canopy.config import Config

OVERSEER = "overseer.md"
WORKER = {"implement": "worker-implement.md", "fix-ci": "worker-fix-ci.md", "resume": "worker-resume.md"}
_PLACEHOLDER_RE = re.compile(r"\{\{([A-Z][A-Z0-9_]*)\}\}")


class PromptError(Exception):
    """A prompt file cannot be rendered."""


@dataclass(frozen=True)
class Capacity:
    """How many workers may run, and how many are running."""

    max_workers: int
    running: int

    @property
    def available(self) -> int:
        """Workers that may still start."""
        return max(0, self.max_workers - self.running)


def prompt_path(config: Config, name: str) -> Path:
    """Return the prompt file `name`, preferring the operator's override."""
    override = config.paths.prompt_overrides / name
    if override.is_file():
        return override
    return resources.prompts_dir() / name


def state_block(
    config: Config,
    repo_root: Path,
    *,
    tick_id: int,
    dry_run: bool,
    capacity: Capacity,
    running: list[sqlite3.Row],
    tickets: list[sqlite3.Row],
    last_runs: Mapping[str, sqlite3.Row],
) -> str:
    """Render the `## State` section the harness appends to the overseer prompt."""
    state = {
        "tick_id": tick_id,
        "dry_run": dry_run,
        "repository": str(repo_root),
        "tracker": {
            "provider": config.tracker.provider,
            "query": config.tracker.query,
            "labels": list(config.tracker.labels),
            "needs_human_label": config.tracker.needs_human_label,
        },
        "trust": {
            "authorized_repliers": list(config.trust.authorized_repliers),
            "branch_prefix": config.trust.branch_prefix,
            "pr_label": config.trust.pr_label,
        },
        "capacity": {
            "max_workers": capacity.max_workers,
            "running": capacity.running,
            "available": capacity.available,
        },
        "policy": {
            "max_fix_ci_attempts": config.policy.max_fix_ci_attempts,
            "fix_ci_cooldown_minutes": config.policy.fix_ci_cooldown_minutes,
            "max_resume_attempts": config.policy.max_resume_attempts,
        },
        "running_workers": [
            {
                "run_id": r["id"],
                "ticket": r["ticket_key"],
                "kind": r["kind"],
                "branch": r["branch"],
                "started_at": r["started_at"],
            }
            for r in running
        ],
        "tickets": [
            {
                "key": t["key"],
                "phase": t["phase"],
                "branch": t["branch"],
                "pr_url": t["pr_url"],
                "cursors": {name: t[column] for name, column in db.CURSOR_COLUMNS.items()},
                "fix_ci_attempts": t["fix_ci_attempts"],
                "resume_attempts": t["resume_attempts"],
                "cooldown_until": t["cooldown_until"],
                "needs_human_since": t["needs_human_since"],
                "last_seen_at": t["last_seen_at"],
                "last_run": _run_summary(last_runs.get(str(t["key"]))),
            }
            for t in tickets
        ],
    }
    if dry_run:
        mode = (
            "This is a dry run. `canopy dispatch` records what it would have done and starts nothing, and "
            "`canopy ticket set` records phases but does not advance cursors. Decide exactly as you would otherwise."
        )
    else:
        mode = "This is a live tick."
    return "\n".join(
        [
            "## State",
            "",
            "Generated by the harness for this tick. It is the journal's view of what the loop did,",
            "not what is true now.",
            "",
            mode,
            "",
            "```json",
            json.dumps(state, indent=2),
            "```",
            "",
        ]
    )


def _run_summary(run: sqlite3.Row | None) -> dict[str, object] | None:
    if run is None:
        return None
    return {
        "run_id": run["id"],
        "kind": run["kind"],
        "status": run["status"],
        "branch": run["branch"],
        "started_at": run["started_at"],
        "ended_at": run["ended_at"],
    }


def render_overseer(config: Config, block: str) -> str:
    """Return the overseer prompt followed by the state block."""
    body = prompt_path(config, OVERSEER).read_text(encoding="utf-8").rstrip("\n")
    return f"{body}\n\n{block}"


def render_worker(config: Config, kind: str, values: Mapping[str, str]) -> str:
    """Return the worker prompt for `kind` with every `{{NAME}}` replaced from `values`.

    Replacement is one pass, so a value that itself contains `{{NAME}}` is left as it is. A placeholder with no value
    is an error: an override with a typo must not reach a worker half rendered.
    """
    path = prompt_path(config, WORKER[kind])
    text = path.read_text(encoding="utf-8")

    def replace(m: re.Match[str]) -> str:
        name = m.group(1)
        if name not in values:
            raise PromptError(f"{path}: unknown placeholder {{{{{name}}}}}")
        return values[name]

    return _PLACEHOLDER_RE.sub(replace, text)
