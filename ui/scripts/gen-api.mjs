// Generates src/api/schema.gen.ts from the FastAPI app's OpenAPI schema (the modules of
// canopy/serve/schema/ are the source).
//
//   npm run gen:api     write it
//   npm run check:api   fail if it is out of date (CI and `npm run check` run this)
//
// The schema comes from `python -m canopy.serve openapi`, which builds the app without starting a server.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import openapiTS, { astToString } from 'openapi-typescript'

const ui = resolve(import.meta.dirname, '..')
const out = resolve(ui, 'src/api/schema.gen.ts')
const check = process.argv.includes('--check')

const schema = execFileSync('uv', ['run', '--quiet', 'python', '-m', 'canopy.serve', 'openapi'], {
    cwd: resolve(ui, '..'),
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
})
const ast = await openapiTS(JSON.parse(schema), { exportType: true, alphabetize: true })
const header =
    "// Generated by `npm run gen:api` from canopy.serve's OpenAPI schema. Do not edit; change\n" +
    '// the model in src/canopy/serve/schema/, and regenerate.\n\n'
const text = header + astToString(ast)

if (check) {
    let current = ''
    try {
        current = readFileSync(out, 'utf8')
    } catch {
        // Missing counts as out of date.
    }
    if (current !== text) {
        console.error('src/api/schema.gen.ts is out of date with canopy.serve; run `npm run gen:api` in ui/.')
        process.exit(1)
    }
    console.log('src/api/schema.gen.ts is up to date.')
} else {
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
}
