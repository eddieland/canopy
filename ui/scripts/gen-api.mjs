// Generates src/api/schema.gen.ts from the FastAPI app's OpenAPI schema (the modules of
// canopy/serve/schema/ are the source). The file is not committed: `npm run gen` (make ui-gen) writes it when the
// Python it comes from is newer, and `npm run lint` and `typecheck` run that first.
//
// The schema comes from `python -m canopy.serve openapi`, which builds the app without starting a server.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import openapiTS, { astToString } from 'openapi-typescript'

const ui = resolve(import.meta.dirname, '..')
const out = resolve(ui, 'src/api/schema.gen.ts')

const schema = execFileSync('uv', ['run', '--quiet', 'python', '-m', 'canopy.serve', 'openapi'], {
    cwd: resolve(ui, '..'),
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
})
const ast = await openapiTS(JSON.parse(schema), { exportType: true, alphabetize: true })
const header =
    "// Generated by `npm run gen` from canopy.serve's OpenAPI schema, and not committed. Do not\n" +
    '// edit; change the model in src/canopy/serve/schema/.\n\n'
const text = header + astToString(ast)

writeFileSync(out, text)
console.log(`wrote ${out}`)
